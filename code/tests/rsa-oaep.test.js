const { expect } = require("chai");
const { ethers } = require("hardhat");
const crypto = require("node:crypto");
const { createAccessKeyPair, encryptAccessKey, decryptAccessKey, labelFor, oaepEncode } = require("./lib/access-envelope");

describe("RSA-OAEP-SHA256 public re-encryption", function () {
  let harness, keys, provider;
  before(async function () {
    [,provider] = await ethers.getSigners(); keys=createAccessKeyPair();
    harness=await(await ethers.getContractFactory("RSAOAEPHarness")).deploy();
  });
  it("matches encoded messages and RSA ciphertext while OpenSSL independently decrypts them",async function () {
    for(let i=0;i<8;++i) {
      const key=crypto.randomBytes(32), seed=crypto.randomBytes(32), label=labelFor(provider.address,i+1);
      const labelHash=crypto.createHash("sha256").update(label).digest();
      expect(await harness.encode(key,seed,labelHash)).to.equal(ethers.hexlify(oaepEncode(key,seed,label)));
      const envelope=encryptAccessKey(key,keys.publicKey,provider.address,i+1,seed);
      expect(await harness.encrypt(key,seed,labelHash,keys.publicKey)).to.equal(ethers.hexlify(envelope));
      expect(decryptAccessKey(envelope,keys.privateKey,provider.address,i+1,ethers.keccak256(key)).equals(key)).to.equal(true);
    }
  });
  it("reproduces ciphertext generated by OpenSSL's complete OAEP implementation",async function () {
    for(let i=0;i<4;++i) {
      const key=crypto.randomBytes(32), label=labelFor(provider.address,i+1);
      const envelope=crypto.publicEncrypt({key:crypto.createPublicKey({key:keys.publicKey,type:"spki",format:"der"}),
        padding:crypto.constants.RSA_PKCS1_OAEP_PADDING,oaepHash:"sha256",oaepLabel:label},key);
      // Extract the random opening only inside this test using the generated private key.
      const em=crypto.privateDecrypt({key:keys.privateKey,padding:crypto.constants.RSA_NO_PADDING},envelope);
      const seedMask=crypto.createHash("sha256").update(em.subarray(33)).update(Buffer.alloc(4)).digest();
      const seed=Buffer.from(em.subarray(1,33));for(let j=0;j<32;++j) seed[j]^=seedMask[j];
      expect(await harness.encrypt(key,seed,crypto.createHash("sha256").update(label).digest(),keys.publicKey))
        .to.equal(ethers.hexlify(envelope));
    }
  });
  it("rejects unsupported or malformed public-key encodings",async function () {
    expect(await harness.validPublicKey(keys.publicKey)).to.equal(true);
    for(const index of [0,32,33,288,293]) {
      const bad=Buffer.from(keys.publicKey);
      if(index===33) bad[index]=1;else if(index===288) bad[index]&=254;else bad[index]^=1;
      expect(await harness.validPublicKey(bad)).to.equal(false);
    }
    expect(await harness.validPublicKey(keys.publicKey.subarray(1))).to.equal(false);
  });
});
