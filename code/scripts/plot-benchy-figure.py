"""Generate the three-panel 3DBenchy figure (Figure fig:benchy_artifact) from the corpus file.

Usage (repository root or anywhere):
  .venv/Scripts/python.exe research/stage-05-ovc-arxiv-revision/code/scripts/plot-benchy-figure.py

Panel (a) prints verbatim lines of the corpus PrusaSlicer output, located by line number and
checked against the file; panel (b) draws its extrusion moves, arcs included; panel (c) is the
photograph of a printed 3DBenchy carried over from the first version of the paper
(paper/figure-sources/benchy_photo.png, extracted losslessly from the v1 figure).
Output: paper/latex/img/benchy_figure.pdf
"""
import hashlib
import math
import re
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from matplotlib.collections import LineCollection
from matplotlib.gridspec import GridSpec
from PIL import Image

STAGE = Path(__file__).resolve().parents[2]
GCODE = STAGE / 'data/corpus/generated/gcode/prusa/benchy.gcode'
GCODE_SHA256 = '291a6eeda17b1b383989fa63a798afa8cd72824fec4c03ac241f1d37885bc8e8'
PHOTO = STAGE / 'paper/figure-sources/benchy_photo.png'
OUT = STAGE / 'paper/latex/img/benchy_figure.pdf'

# (line number, expected prefix, role); None marks an elision between non-adjacent lines
EXCERPT = [
    (1, '; generated by PrusaSlicer 2.9.6', 'comment'),
    (29, 'G90 ; use absolute coordinates', None),
    (30, 'M83 ; extruder relative mode', None),
    (36, 'M140 S60 ; set bed temp', None),
    (40, 'G28 XY', None),
    (71, 'G92 E0 ; reset extruder position', 'datum'),
    None,
    (91, 'G1 E-.8 F2100', 'retract'),
    (96, 'G1 E.8 F1500', None),
    None,
    (101, 'G1 X183.97 Y161.786 E.01141', 'motion'),
    (102, 'G3 X186.001 Y161.837 I.821 J7.759 E.07744', 'motion'),
    (103, 'G1 X186.388 Y161.956 E.01539', 'motion'),
]
ROLE_COLOR = {'comment': '#888888', 'datum': '#7a4f00', 'retract': '#c0392b', 'motion': '#1a6faf'}
# (excerpt row pointed at, row of the label, label, face color, edge color)
ANNOTATIONS = [
    (5, 5, 'G92: re-datums E,\nno extrusion', '#fff3cd', '#c07000'),
    (10, 9.2, 'OVC-Conformance\nchecks G0/G1 presence', '#ddeeff', '#1a6faf'),
    (11, 12.0, 'OVC-Feature sums\nE over G0-G3 moves', '#fff3cd', '#c07000'),
]


def read_lines():
    data = GCODE.read_bytes()
    assert hashlib.sha256(data).hexdigest() == GCODE_SHA256, 'corpus file differs from the release'
    return data.decode('ascii').split('\n')


def draw_gcode_panel(ax, lines):
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis('off')
    ax.add_patch(mpatches.FancyBboxPatch((0.01, 0.01), 0.70, 0.98, boxstyle='round,pad=0.01',
                                         facecolor='#f8f8f8', edgecolor='#cccccc', linewidth=0.8,
                                         transform=ax.transAxes, clip_on=False))
    row_h = 1.0 / (len(EXCERPT) + 2)
    for i, item in enumerate(EXCERPT):
        y = 1.0 - (i + 1.2) * row_h
        if item is None:
            ax.text(0.10, y, '...', transform=ax.transAxes, fontsize=7, fontfamily='monospace',
                    color='#888888', va='center')
            continue
        number, expected, role = item
        text = lines[number - 1].rstrip('\r')
        assert text.startswith(expected), (number, text)
        text = expected if role == 'comment' else text  # the header line also carries a timestamp
        ax.text(0.02, y, f'{number:>3}', transform=ax.transAxes, fontsize=6, fontfamily='monospace',
                color='#aaaaaa', va='center')
        ax.text(0.085, y, text, transform=ax.transAxes, fontsize=6.0, fontfamily='monospace',
                color=ROLE_COLOR.get(role, '#222222'), va='center')
    for row, label_row, label, face, edge in ANNOTATIONS:
        y, label_y = (1.0 - (r + 1.2) * row_h for r in (row, label_row))
        ax.annotate(label, xy=(0.72, y), xycoords='axes fraction', xytext=(0.77, label_y),
                    textcoords='axes fraction', fontsize=5.6, ha='left', va='center',
                    bbox=dict(boxstyle='round,pad=0.3', facecolor=face, edgecolor=edge, linewidth=0.9),
                    arrowprops=dict(arrowstyle='-|>', color=edge, lw=0.9))
    ax.set_title('(a) G-code excerpt (3DBenchy, PrusaSlicer 2.9.6,\n0.10 mm layers, PLA; line numbers left)',
                 fontsize=8, pad=4)


WORD = re.compile(r'([A-Z])(-?[\d.]+)')


def arc_points(x0, y0, x1, y1, i, j, clockwise):
    cx, cy = x0 + i, y0 + j
    r = math.hypot(i, j)
    a0, a1 = math.atan2(y0 - cy, x0 - cx), math.atan2(y1 - cy, x1 - cx)
    sweep = a1 - a0
    if clockwise and sweep >= 0:
        sweep -= 2 * math.pi
    if not clockwise and sweep <= 0:
        sweep += 2 * math.pi
    steps = max(2, int(abs(sweep) * r / 0.2))
    return [(cx + r * math.cos(a0 + sweep * k / steps), cy + r * math.sin(a0 + sweep * k / steps))
            for k in range(1, steps + 1)]


def toolpath(lines):
    """Extruding segments per layer; layers follow the slicer's ;Z: markers, so Z-hops are ignored."""
    layers, z = {}, None
    x = y = 0.0
    for raw in lines:
        if raw.startswith(';Z:'):
            z = float(raw[3:])
            continue
        code = raw.split(';', 1)[0].strip()
        if not code or code[0] != 'G':
            continue
        head = code.split()[0]
        if head not in ('G0', 'G1', 'G2', 'G3'):
            continue
        words = {k: float(v) for k, v in WORD.findall(code[len(head):])}
        nx, ny = words.get('X', x), words.get('Y', y)
        if z is not None and words.get('E', 0) > 0 and (nx, ny) != (x, y):
            if head in ('G2', 'G3'):
                pts = [(x, y)] + arc_points(x, y, nx, ny, words.get('I', 0), words.get('J', 0), head == 'G2')
            else:
                pts = [(x, y), (nx, ny)]
            layers.setdefault(z, []).extend(zip(pts[:-1], pts[1:]))
        x, y = nx, ny
    return layers


def draw_toolpath_panel(fig, ax, layers):
    zs = sorted(layers)
    selected = zs[::max(1, len(zs) // 30)]
    cmap = plt.cm.viridis
    for k, z in enumerate(selected):
        ax.add_collection(LineCollection(layers[z], colors=[cmap(k / max(len(selected) - 1, 1))],
                                         linewidths=0.25, alpha=0.7))
    ax.autoscale()
    ax.set_aspect('equal')
    ax.set_xlabel('X (mm)', fontsize=7)
    ax.set_ylabel('Y (mm)', fontsize=7)
    ax.tick_params(labelsize=6)
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=plt.Normalize(vmin=zs[0], vmax=zs[-1]))
    cbar = fig.colorbar(sm, ax=ax, fraction=0.046, pad=0.04)
    cbar.set_label('Z height (mm)', fontsize=6)
    cbar.ax.tick_params(labelsize=5)
    ax.set_title('(b) Toolpath of the same file\n(extrusion moves, top view, layers colored by height)',
                 fontsize=8, pad=4)


def draw_photo_panel(ax):
    ax.imshow(Image.open(PHOTO))
    ax.axis('off')
    ax.set_title('(c) Manufactured artifact\n(printed 3DBenchy, PLA)', fontsize=8, pad=4)


def main():
    lines = read_lines()
    fig = plt.figure(figsize=(13, 4.5))
    gs = GridSpec(1, 3, figure=fig, wspace=0.35, left=0.04, right=0.97, top=0.92, bottom=0.05)
    draw_gcode_panel(fig.add_subplot(gs[0]), lines)
    draw_toolpath_panel(fig, fig.add_subplot(gs[1]), toolpath(lines))
    draw_photo_panel(fig.add_subplot(gs[2]))
    fig.savefig(OUT, dpi=300, bbox_inches='tight')
    print(f'Saved {OUT}')


if __name__ == '__main__':
    main()
